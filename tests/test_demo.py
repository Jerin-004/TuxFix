"""Tests for demo mode — must never pretend to be a real LLM."""
from __future__ import annotations

import json
import pytest

from tuxfix.demo import (
    DEMO_NOTICE,
    get_demo_response,
    get_demo_responses_for_all_strategies,
)
from tuxfix.schemas import parse_model_response


class TestDemoResponses:
    def test_demo_notice_present_in_all_responses(self):
        for kw in ["networking", "package management", "unknown error"]:
            resp = get_demo_response(kw)
            # Either the notice itself or DEMO MODE marker must be present
            assert "DEMO" in resp or "demo" in resp.lower()

    def test_demo_response_is_valid_json(self):
        resp = get_demo_response("DNS failure")
        data = json.loads(resp)
        assert "problem_summary" in data

    def test_demo_response_parses_to_schema(self):
        resp = get_demo_response("DNS failure networking")
        result = parse_model_response(resp)
        assert result.success is True, f"Failed: {result.error_message}"

    def test_networking_keyword_selects_networking_response(self):
        resp = get_demo_response("DNS networking ping failure")
        data = json.loads(resp)
        assert data["problem_category"] == "networking"

    def test_package_keyword_selects_package_response(self):
        resp = get_demo_response("apt install package repository error")
        data = json.loads(resp)
        assert data["problem_category"] == "package_management"

    def test_default_category_for_unknown(self):
        resp = get_demo_response("some random unrelated text xyz123")
        data = json.loads(resp)
        assert data["problem_category"] in ("other", "networking", "package_management")

    def test_all_strategies_demo_responses(self):
        results = get_demo_responses_for_all_strategies()
        assert len(results) == 5
        for strategy, resp in results.items():
            assert resp is not None
            assert len(resp) > 10

    def test_demo_limitations_contain_notice(self):
        resp = get_demo_response("any problem")
        data = json.loads(resp)
        limitations = data.get("limitations", "")
        assert "DEMO" in limitations or "demo" in limitations.lower()


class TestDemoModeNotice:
    def test_demo_notice_string_is_clear(self):
        assert "NOT generated by a real LLM" in DEMO_NOTICE
        assert "DEMO MODE" in DEMO_NOTICE
