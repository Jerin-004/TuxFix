"""Tests for LLM client — all network calls are mocked."""
from __future__ import annotations

import json
from unittest.mock import MagicMock, patch

import pytest
import requests

from tuxfix.config import TuxFixConfig
from tuxfix.llm_client import (
    DemoProvider,
    LLMError,
    LLMResponse,
    OllamaProvider,
    get_provider,
)


class TestOllamaProvider:
    @pytest.fixture
    def config(self):
        return TuxFixConfig(
            ollama_base_url="http://localhost:11434",
            ollama_model="test-model",
            ollama_timeout=10,
        )

    @pytest.fixture
    def provider(self, config):
        return OllamaProvider(config)

    def test_is_available_true(self, provider):
        with patch("requests.get") as mock_get:
            mock_get.return_value = MagicMock(status_code=200)
            assert provider.is_available() is True

    def test_is_available_false_on_connection_error(self, provider):
        with patch("requests.get", side_effect=requests.ConnectionError()):
            assert provider.is_available() is False

    def test_list_models(self, provider):
        mock_resp = MagicMock(status_code=200)
        mock_resp.json.return_value = {"models": [{"name": "llama3"}, {"name": "mistral"}]}
        with patch("requests.get", return_value=mock_resp):
            models = provider.list_models()
        assert "llama3" in models
        assert "mistral" in models

    def test_list_models_empty_on_error(self, provider):
        with patch("requests.get", side_effect=requests.ConnectionError()):
            models = provider.list_models()
        assert models == []

    def test_generate_success(self, provider, valid_report_json_str):
        mock_resp = MagicMock(status_code=200)
        mock_resp.json.return_value = {
            "response": valid_report_json_str,
            "model": "test-model",
            "eval_count": 100,
            "prompt_eval_count": 50,
        }
        with patch("requests.post", return_value=mock_resp):
            response = provider.generate("test prompt")
        assert response.text == valid_report_json_str
        assert response.model == "test-model"
        assert response.token_count == 100
        assert response.is_demo is False

    def test_generate_connection_error(self, provider):
        with patch("requests.post", side_effect=requests.ConnectionError("refused")):
            with pytest.raises(LLMError, match="Cannot connect"):
                provider.generate("test prompt")

    def test_generate_timeout(self, provider):
        with patch("requests.post", side_effect=requests.Timeout()):
            with pytest.raises(LLMError, match="timed out"):
                provider.generate("test prompt")

    def test_generate_http_error(self, provider):
        mock_resp = MagicMock(status_code=404)
        mock_resp.json.return_value = {"error": "model not found"}
        with patch("requests.post", return_value=mock_resp):
            with pytest.raises(LLMError, match="HTTP 404"):
                provider.generate("test prompt")

    def test_generate_empty_response(self, provider):
        mock_resp = MagicMock(status_code=200)
        mock_resp.json.return_value = {"response": "", "model": "test"}
        with patch("requests.post", return_value=mock_resp):
            with pytest.raises(LLMError, match="empty"):
                provider.generate("test prompt")


class TestDemoProvider:
    @pytest.fixture
    def provider(self):
        return DemoProvider()

    def test_always_available(self, provider):
        assert provider.is_available() is True

    def test_list_models_returns_demo(self, provider):
        models = provider.list_models()
        assert len(models) > 0
        assert "demo" in models[0].lower()

    def test_generate_returns_response(self, provider):
        resp = provider.generate("a networking problem")
        assert isinstance(resp, LLMResponse)
        assert resp.is_demo is True
        assert resp.provider == "demo"

    def test_demo_response_is_json(self, provider):
        resp = provider.generate("DNS failure networking problem")
        data = json.loads(resp.text)
        assert "problem_summary" in data

    def test_demo_response_labelled(self, provider):
        resp = provider.generate("some prompt")
        assert "DEMO MODE" in resp.text or "demo" in resp.text.lower()

    def test_demo_not_claimed_real(self, provider):
        resp = provider.generate("networking issue")
        # The response must contain the demo notice
        assert "NOT generated by a real LLM" in resp.text or "DEMO MODE" in resp.text

    def test_demo_picks_networking_response(self, provider):
        resp = provider.generate("ping: google.com: name resolution failed")
        data = json.loads(resp.text)
        assert data["problem_category"] == "networking"


class TestGetProvider:
    def test_demo_mode_returns_demo_provider(self):
        config = TuxFixConfig(demo_mode=True)
        provider = get_provider(config)
        assert isinstance(provider, DemoProvider)

    def test_real_mode_returns_ollama_provider(self):
        config = TuxFixConfig(demo_mode=False)
        provider = get_provider(config)
        assert isinstance(provider, OllamaProvider)
